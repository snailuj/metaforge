"""Metaphor Enrichment Spike — Phase 2 runner (cohort scale-up).

200 anchor topics × Haiku-only × 2 prompts ≈ 400 LLM calls. Uses the
exact same Sonnet-as-prompt-engineer apt/inapt templates baked in
Phase 1b — only the topic source differs.

Topic source: ``data-pipeline/scripts/spike_2_topics.json`` (built by
``curate_spike_2_topics.py``). 20 hand-curated spine topics from
Phase 1b + 180 sampled across three concreteness bands.

Phase 2 produces the **evaluation cohort** for M05 calibration close-
out, plus the per-`inapt_reason_type` discrimination breakdown at
real scale. The follow-up metric correction (end-to-end aptness
against the full cohort, not just scored pairs) and concept
lemmatisation are deliberately deferred — see
``docs/inbox/2026-05-25-metaphor-spike-findings.md``.

Usage::

    python data-pipeline/scripts/metaphor_spike_2.py \\
        --db data-pipeline/output/lexicon_v2.db \\
        --topics data-pipeline/scripts/spike_2_topics.json \\
        --output-dir data-pipeline/output

Outputs (written to --output-dir; <TS> = YYYYMMDDTHHMMSS)::

    metaphor_spike_apt_phase2_<TS>.jsonl
    metaphor_spike_inapt_phase2_<TS>.jsonl
    metaphor_spike_scores_phase2_<TS>.jsonl
    metaphor_spike_scoring_phase2_<TS>.md
"""
